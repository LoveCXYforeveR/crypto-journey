"""一次性脚本：从 src/sm4.py 读 SBOX/FK/CK，生成 C 常量表源码。

用法（仓库根目录下）：
    python tools/gen_constants.py
输出：
    c/constants.h  —— 被 c/sm4.c #include
同时在 stdout 打印长度自检。
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

import sm4  # noqa: E402


def fmt_u8_row(values, per_row=16):
    out = []
    for i in range(0, len(values), per_row):
        chunk = values[i:i + per_row]
        out.append("    " + ", ".join(f"0x{v:02X}" for v in chunk) + ",")
    # 去掉最后一行末尾逗号（C 允许尾随逗号，保留也无妨；这里保留以省事）
    return "\n".join(out)


def fmt_u32_row(values, per_row=4):
    out = []
    for i in range(0, len(values), per_row):
        chunk = values[i:i + per_row]
        out.append("    " + ", ".join(f"0x{v:08X}u" for v in chunk) + ",")
    return "\n".join(out)


def main():
    sbox = list(sm4.SBOX)
    fk = list(sm4.FK)
    ck = list(sm4.CK)

    # 自检长度
    assert len(sbox) == 256, f"SBOX length {len(sbox)} != 256"
    assert len(fk) == 4, f"FK length {len(fk)} != 4"
    assert len(ck) == 32, f"CK length {len(ck)} != 32"
    # 自检值域
    assert all(0 <= v <= 0xFF for v in sbox), "SBOX byte out of range"
    assert all(0 <= v <= 0xFFFFFFFF for v in fk), "FK out of uint32 range"
    assert all(0 <= v <= 0xFFFFFFFF for v in ck), "CK out of uint32 range"

    header = f"""/* AUTO-GENERATED by tools/gen_constants.py — DO NOT EDIT BY HAND.
 * Source of truth: src/sm4.py (SBOX / FK / CK).
 * Regenerate with:  python tools/gen_constants.py
 */
#ifndef SM4_CONSTANTS_H
#define SM4_CONSTANTS_H

#include <stdint.h>

static const uint8_t SBOX[256] = {{
{fmt_u8_row(sbox)}
}};

static const uint32_t FK[4] = {{
{fmt_u32_row(fk)}
}};

static const uint32_t CK[32] = {{
{fmt_u32_row(ck)}
}};

#endif /* SM4_CONSTANTS_H */
"""

    out_path = REPO / "c" / "constants.h"
    out_path.write_text(header, encoding="utf-8", newline="\n")

    print(f"[ok] SBOX length = {len(sbox)} (expect 256)")
    print(f"[ok] FK   length = {len(fk)} (expect 4)")
    print(f"[ok] CK   length = {len(ck)} (expect 32)")
    print(f"[ok] wrote {out_path}")
    # 顺手打印 FK/CK 头几项做肉眼核对
    print(f"[chk] FK[0..3] = {[hex(x) for x in fk]}")
    print(f"[chk] CK[0..3] = {[hex(x) for x in ck[:4]]}")
    print(f"[chk] SBOX[0..3] = {[hex(x) for x in sbox[:4]]}  (expect d6 90 e9 fe)")


if __name__ == "__main__":
    main()
