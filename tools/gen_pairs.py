"""生成 pairs.json：Python 版加密 1000 个随机 block 的 ground truth。

C 版 test_sm4.c 会读这个文件，逐字节比对。
固定随机种子，保证可复现。
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

import sm4  # noqa: E402

KEY = bytes.fromhex("0123456789abcdeffedcba9876543210")
N = 1000
SEED = 20261027


def main():
    import random
    rng = random.Random(SEED)
    pairs = []
    for _ in range(N):
        plain = bytes(rng.getrandbits(8) for _ in range(16))
        cipher = sm4.encrypt_block(KEY, plain)
        pairs.append({
            "plain_hex": plain.hex(),
            "cipher_hex": cipher.hex(),
        })
    out = {
        "key_hex": KEY.hex(),
        "note": f"{N} random blocks, seed={SEED}, generated by tools/gen_pairs.py",
        "pairs": pairs,
    }
    out_path = REPO / "data" / "vectors" / "sm4_pairs.json"
    out_path.write_text(json.dumps(out, indent=2), encoding="utf-8", newline="\n")
    print(f"[ok] wrote {out_path} with {len(pairs)} pairs")


if __name__ == "__main__":
    main()
