"""SM4 分组密码算法（GB/T 32907-2016）纯 Python 实现。

- 密钥/明文/密文均为 16 字节分组
- 32 轮迭代，加解密结构完全相同，仅轮密钥顺序相反
- 仅使用标准库，不依赖任何密码库

关键结构点:
1. 密钥扩展: K[i] = MK[i] XOR FK[i]，再按 rk[i] = K[i] ^ T'(K[i+1]^K[i+2]^K[i+3]^CK[i])
   T' 的线性部分是 L'(B) = B ^ rotl(B,13) ^ rotl(B,23)（与加密轮 T 的 L 不同，抄错必炸）。
2. 加密轮: X[i+4] = X[i] ^ T(X[i+1]^X[i+2]^X[i+3]^rk[i])，共 32 轮。
3. 最后一轮结构差异: 完整执行 32 轮 T 后，输出按 X[35],X[34],X[33],X[32]
   反序拼回 16 字节。等价写法是「最后一轮省去 L 变换后反序输出」，
   因为 L 是线性变换且输出只取反序后的 4 个字；本实现采用标准完整轮 + 反序输出。
4. 解密: 把轮密钥反序 (rk[31], rk[30], ..., rk[0]) 复用同一轮函数。
"""

