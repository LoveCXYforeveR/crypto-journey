_MASK32 = 0xFFFFFFFF


def _rotl(x: int, n: int) -> int:
    """32 位循环左移。"""
    return ((x << n) | (x >> (32 - n))) & _MASK32


def _tau(x: int) -> int:
    """非线性变换 τ: 32 位字拆 4 字节过 S 盒再拼回。"""
    return (
        (SBOX[(x >> 24) & 0xFF] << 24)
        | (SBOX[(x >> 16) & 0xFF] << 16)
        | (SBOX[(x >> 8) & 0xFF] << 8)
        | SBOX[x & 0xFF]
    )


def _l(b: int) -> int:
    """加密轮线性变换 L(B) = B ^ rotl(B,2) ^ rotl(B,10) ^ rotl(B,18) ^ rotl(B,24)。"""
    return b ^ _rotl(b, 2) ^ _rotl(b, 10) ^ _rotl(b, 18) ^ _rotl(b, 24)


def _lp(b: int) -> int:
    """密钥扩展线性变换 L'(B) = B ^ rotl(B,13) ^ rotl(B,23)。"""
    return b ^ _rotl(b, 13) ^ _rotl(b, 23)


def _check_16(name: str, data: bytes) -> None:
    if not isinstance(data, (bytes, bytearray)):
        raise TypeError(f"{name} 必须是 bytes")
    if len(data) != 16:
        raise ValueError(f"{name} 长度必须为 16 字节，实际 {len(data)} 字节")


def key_schedule(key: bytes) -> list:
    """密钥扩展: 16 字节密钥 -> 32 个 32 位轮密钥 rk[0..31]。

    可独立调用/独立测试。
    """
    _check_16("密钥", key)
    mk = [int.from_bytes(key[i * 4:(i + 1) * 4], "big") for i in range(4)]
    k = [mk[i] ^ FK[i] for i in range(4)]
    rks = []
    for i in range(32):
        t = _lp(_tau(k[1] ^ k[2] ^ k[3] ^ CK[i]))
        rk = k[0] ^ t
        rks.append(rk)
        k = [k[1], k[2], k[3], rk]
    return rks


def _crypt_block(rks: list, block: bytes) -> bytes:
    """按给定轮密钥顺序加密/解密一个 16 字节分组。"""
    x = [int.from_bytes(block[i * 4:(i + 1) * 4], "big") for i in range(4)]
    for rk in rks:
        t = _l(_tau(x[1] ^ x[2] ^ x[3] ^ rk))
        x = [x[1], x[2], x[3], x[0] ^ t]
    # 32 轮后按 X[35],X[34],X[33],X[32] 反序输出
    return b"".join(w.to_bytes(4, "big") for w in (x[3], x[2], x[1], x[0]))


def encrypt_block(key: bytes, block: bytes) -> bytes:
    """SM4 加密一个 16 字节分组。"""
    _check_16("明文块", block)
    return _crypt_block(key_schedule(key), block)


def decrypt_block(key: bytes, block: bytes) -> bytes:
    """SM4 解密一个 16 字节分组（轮密钥反序复用同一轮函数）。"""
    _check_16("密文块", block)
    return _crypt_block(list(reversed(key_schedule(key))), block)
